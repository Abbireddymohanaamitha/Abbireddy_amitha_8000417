package com.practice.basics;

/**
 * 6. Data Type Demonstration
 * Shows primitive types and simple initialization.
 */
public class DataTypeDemo {
    public static void main(String[] args) {
        int count = 25;
        double price = 19.99;
        char symbol = 'J';
        boolean isJavaFun = true;

        System.out.println("Integer value: " + count);
        System.out.println("Double value: " + price);
        System.out.println("Character value: " + symbol);
        System.out.println("Boolean value: " + isJavaFun);
        System.out.println("Note: Java uses strong typing and each variable stores a specific data type.");
    }
}
